#!/usr/bin/env node
// Generates lib/core/api/api_models.dart from the API's OpenAPI document
// (packages/api-client/openapi.json). Re-run after API changes:
//   node apps/mobile/tool/gen_api_models.mjs
// The output is plain Dart (no build_runner) and is committed.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const specPath = resolve(here, '../../../packages/api-client/openapi.json');
const outPath = resolve(here, '../lib/core/api/api_models.dart');
const spec = JSON.parse(readFileSync(specPath, 'utf8'));
const schemas = spec.components.schemas;

const RESERVED = new Set([
  'default', 'class', 'in', 'is', 'new', 'enum', 'with', 'switch', 'case', 'var', 'final',
  'const', 'void', 'null', 'true', 'false', 'this', 'super', 'return', 'if', 'else', 'for',
  'do', 'while', 'try', 'catch', 'throw', 'assert', 'extends', 'import', 'export',
]);

const refName = (ref) => ref.split('/').pop();
const fieldName = (n) => (RESERVED.has(n) ? `${n}_` : n);

/** Returns { type, parse(expr), toJson(expr) } for a property schema (non-null form). */
function typeOf(p) {
  if (p.$ref) {
    const n = refName(p.$ref);
    return { type: n, parse: (e) => `${n}.fromJson(_map(${e}))`, toJson: (e) => `${e}.toJson()` };
  }
  if (p.allOf && p.allOf.length === 1 && p.allOf[0].$ref) return typeOf(p.allOf[0]);
  switch (p.type) {
    case 'string':
      return { type: 'String', parse: (e) => `${e} as String`, toJson: (e) => e };
    case 'number':
    case 'integer':
      return { type: 'num', parse: (e) => `${e} as num`, toJson: (e) => e };
    case 'boolean':
      return { type: 'bool', parse: (e) => `${e} as bool`, toJson: (e) => e };
    case 'array': {
      const it = typeOf(p.items ?? {});
      return {
        type: `List<${it.type}>`,
        parse: (e) => `(${e} as List<dynamic>).map((dynamic x) => ${it.parse('x')}).toList()`,
        toJson: (e) => (it.toJson('x') === 'x' ? e : `${e}.map((x) => ${it.toJson('x')}).toList()`),
      };
    }
    case 'object':
      if (p.additionalProperties && p.additionalProperties.type === 'string') {
        return {
          type: 'Map<String, String>',
          parse: (e) => `(${e} as Map<String, dynamic>).map((k, dynamic v) => MapEntry(k, v as String))`,
          toJson: (e) => e,
        };
      }
      return { type: 'Map<String, dynamic>', parse: (e) => `_map(${e})`, toJson: (e) => e };
    default:
      return { type: 'Object', parse: (e) => `${e} as Object`, toJson: (e) => e };
  }
}

const out = [];
out.push('// GENERATED by tool/gen_api_models.mjs from packages/api-client/openapi.json.');
out.push('// Do not edit by hand. Re-run the generator after API changes.');
out.push('// ignore_for_file: lines_longer_than_80_chars, unnecessary_lambdas');
out.push('');
out.push("import 'package:flutter/foundation.dart';");
out.push('');
out.push('Map<String, dynamic> _map(Object? v) => (v as Map).cast<String, dynamic>();');
out.push('');

for (const name of Object.keys(schemas).sort()) {
  const s = schemas[name];
  const props = s.properties ?? {};
  const required = new Set(s.required ?? []);
  const fields = Object.entries(props).map(([key, p]) => {
    const t = typeOf(p);
    const nullable = !required.has(key) || p.nullable === true;
    return { key, name: fieldName(key), t, nullable, desc: p.description, enumValues: p.enum ?? p.items?.enum };
  });
  if (s.description) out.push(`/// ${s.description.replace(/\n/g, ' ')}`);
  out.push('@immutable');
  out.push(`class ${name} {`);
  if (fields.length === 0) {
    out.push(`  const ${name}();`);
  } else {
    out.push(`  const ${name}({`);
    for (const f of fields) out.push(`    ${f.nullable ? '' : 'required '}this.${f.name},`);
    out.push('  });');
  }
  out.push('');
  out.push(`  factory ${name}.fromJson(Map<String, dynamic> json) => ${name}(`);
  for (const f of fields) {
    const access = `json['${f.key}']`;
    out.push(
      f.nullable
        ? `        ${f.name}: ${access} == null ? null : ${f.t.parse(access)},`
        : `        ${f.name}: ${f.t.parse(access)},`,
    );
  }
  out.push('      );');
  out.push('');
  for (const f of fields) {
    const doc = [f.desc?.replace(/</g, '&lt;').replace(/>/g, '&gt;'), f.enumValues ? `One of: ${f.enumValues.join(', ')}.` : null].filter(Boolean).join(' ');
    if (doc) out.push(`  /// ${doc.replace(/\n/g, ' ')}`);
    out.push(`  final ${f.t.type}${f.nullable ? '?' : ''} ${f.name};`);
  }
  if (fields.length) out.push('');
  out.push('  Map<String, dynamic> toJson() => <String, dynamic>{');
  for (const f of fields) {
    if (f.nullable) {
      const v = f.t.toJson(f.name).replace(new RegExp(`^${f.name}\\.`), `${f.name}?.`);
      out.push(`        '${f.key}': ?${v},`);
    } else {
      out.push(`        '${f.key}': ${f.t.toJson(f.name)},`);
    }
  }
  out.push('      };');
  out.push('}');
  out.push('');
}

writeFileSync(outPath, out.join('\n'));
console.log(`wrote ${Object.keys(schemas).length} models to ${outPath}`);
